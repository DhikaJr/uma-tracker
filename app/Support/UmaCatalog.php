    /**
     * Determine evaluation rank given a numerical evaluation score.
     */
    public static function getRankFromScore(int $score): string
    {
        $currentRank = 'G';
        foreach (self::getRankScoreThresholds() as $rank => $minScore) {
            if ($score >= $minScore) {
                $currentRank = $rank;
            } else {
                break;
            }
        }

        return $currentRank;
    }

