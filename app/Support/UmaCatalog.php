    /**
     * Complete list of playable character variants and costumes (all alts from JP & Global server).
     *
     * @return array<int, string>
     */
    public static function getCharacters(): array
    {
        if (self::$cachedCharacters !== null) {
            return self::$cachedCharacters;
        }

        try {
            $charCards = UmaCatalogItem::where('type', 'character')->get();
            if ($charCards->isNotEmpty()) {
                $list = [];
                foreach ($charCards as $card) {
                    $list[$card->name] = true;
                    $raw = $card->raw_data;
                    $nameEn = trim((string) ($raw['name_en'] ?? ''));
                    if ($nameEn === '') {
                        $nameEn = trim(preg_replace('/\s*\[.*?\]$/', '', (string) $card->name));
                    }
                    if ($nameEn !== '' && ! in_array($nameEn, self::NON_PLAYABLE_NAMES, true)) {
                        $list[$nameEn] = true;
                    }
                }
                ksort($list);

                return self::$cachedCharacters = array_keys($list);
            }
        } catch (Throwable) {
            // Fallback if table does not exist
        }

        return self::$cachedCharacters = self::getStaticCharacters();
    }

