    /**
     * List of unique base Uma Musume names for Career runs (Fans Tracker).
     *
     * @return array<int, string>
     */
    public static function getBaseUmaList(): array
    {
        if (self::$cachedBaseUmas !== null) {
            return self::$cachedBaseUmas;
        }

        try {
            $charCards = UmaCatalogItem::where('type', 'character')->get();

            if ($charCards->isNotEmpty()) {
                $roster = [];
                foreach ($charCards as $card) {
                    $raw = $card->raw_data;
                    $nameEn = trim((string) ($raw['name_en'] ?? ''));
                    if ($nameEn === '') {
                        $nameEn = trim(preg_replace('/\s*\[.*?\]$/', '', (string) $card->name));
                    }
                    if ($nameEn === '' || in_array($nameEn, self::NON_PLAYABLE_NAMES, true)) {
                        continue;
                    }

                    $roster[$nameEn] = $nameEn;

                    $version = $raw['version'] ?? null;
                    if ($version) {
                        $label = self::VERSION_LABELS[$version] ?? ucwords(str_replace('_', ' ', (string) $version));
                        $variantName = "{$nameEn} ({$label})";
                        $roster[$variantName] = $variantName;
                    }
                }

                if (! empty($roster)) {
                    ksort($roster);

                    return self::$cachedBaseUmas = array_values($roster);
                }
            }

            $basePlayables = UmaCatalogItem::where('type', 'base_uma')
                ->whereNotIn('name', self::NON_PLAYABLE_NAMES)
                ->pluck('name')
                ->all();

            $seedList = ! empty($basePlayables) ? $basePlayables : self::getStaticBaseUmaList();
            $roster = [];
            foreach ($seedList as $name) {
                if (! in_array($name, self::NON_PLAYABLE_NAMES, true)) {
                    $roster[$name] = $name;
                }
            }

            if (! empty($roster)) {
                ksort($roster);

                return self::$cachedBaseUmas = array_values($roster);
            }
        } catch (Throwable) {
            // Fallback if table does not exist
        }

        return self::$cachedBaseUmas = self::getStaticBaseUmaList();
    }

