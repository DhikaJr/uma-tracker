    /**
     * Complete list of all Support Cards from the Japan Server (SSR, SR, and R).
     *
     * @return array<int, string>
     */
    public static function getSupportCards(): array
    {
        if (self::$cachedCards !== null) {
            return self::$cachedCards;
        }

        try {
            $items = UmaCatalogItem::where('type', 'support_card')->orderBy('name')->pluck('name')->all();
            if (! empty($items)) {
                return self::$cachedCards = $items;
            }
        } catch (Throwable) {
            // Fallback if table does not exist
        }

        return self::$cachedCards = self::getStaticSupportCards();
    }

