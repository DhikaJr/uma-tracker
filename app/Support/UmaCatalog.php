    /**
     * Map of character names to their base pull rarity (SSR / SR / R).
     *
     * @return array<string, string>
     */
    public static function getCharacterRarities(): array
    {
        if (self::$cachedRarities !== null) {
            return self::$cachedRarities;
        }

        $staticRarities = self::getStaticCharacterRarities();

        try {
            $dbRarities = UmaCatalogItem::where('type', 'character')->pluck('rarity', 'name')->all();
            if (! empty($dbRarities)) {
                $staticRarities = array_merge($staticRarities, $dbRarities);
            }
        } catch (Throwable) {
            // Fallback if table does not exist
        }

        // Ensure base character names reflect their initial stars (1★ => R, 2★ => SR)
        foreach (self::BASE_UMA_INITIAL_STARS as $name => $stars) {
            $staticRarities[$name] = $stars === 1 ? 'R' : ($stars === 2 ? 'SR' : 'SSR');
        }

        return self::$cachedRarities = $staticRarities;
    }

