    /**
     * Return star rating mapping for base playable characters.
     *
     * @return array<string, int>
     */
    public static function getBaseUmaStarRatings(): array
    {
        try {
            $items = UmaCatalogItem::where('type', 'character')->get();
            $stars = self::BASE_UMA_INITIAL_STARS;

            foreach ($items as $item) {
                $raw = $item->raw_data;
                if (! is_array($raw)) {
                    continue;
                }
                $version = $raw['version'] ?? null;
                if ($version) {
                    continue; // Skip variant costumes, only base cards
                }
                $nameEn = trim((string) ($raw['name_en'] ?? ''));
                $rarity = (int) ($raw['rarity'] ?? 0);
                if ($nameEn !== '' && $rarity >= 1 && $rarity <= 3) {
                    $stars[$nameEn] = $rarity;
                }
            }

            return $stars;
        } catch (Throwable) {
            return self::BASE_UMA_INITIAL_STARS;
        }
    }

